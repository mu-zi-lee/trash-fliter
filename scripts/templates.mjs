import { readFile, writeFile } from 'node:fs/promises';
import { parseDocument } from 'htmlparser2';

export async function buildTemplates() {
  const markup = await readFile(new URL('../src/ui/panel-template.html', import.meta.url), 'utf8');
  const convert = node => {
    if (node.type === 'text') return node.data.trim() ? node.data : null;
    if (node.type !== 'tag') throw new Error(`Unsupported template node: ${node.type}`);
    return {
      tag: node.name,
      attributes: node.attribs,
      children: node.children.map(convert).filter(node => node !== null),
    };
  };
  const nodes = parseDocument(markup).children.map(convert).filter(node => node !== null);
  await writeFile(new URL('../src/ui/panel-template.js', import.meta.url),
    `// Generated by scripts/templates.mjs from panel-template.html. Do not edit.\nexport default ${JSON.stringify(nodes, null, 2)};\n`);
}
